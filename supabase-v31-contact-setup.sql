create table if not exists public.enquiries (
 id bigint generated by default as identity primary key,
 name text not null, phone text not null, email text, suburb text not null, service text not null, message text,
 images text[] default '{}', status text not null default 'New', created_at timestamptz not null default now()
);
alter table public.enquiries enable row level security;
drop policy if exists "public create enquiries" on public.enquiries;
create policy "public create enquiries" on public.enquiries for insert to anon with check (true);
drop policy if exists "authenticated manage enquiries" on public.enquiries;
create policy "authenticated manage enquiries" on public.enquiries for all to authenticated using (true) with check (true);

insert into storage.buckets (id,name,public) values ('enquiry-images','enquiry-images',true)
on conflict (id) do update set public=true;
drop policy if exists "public upload enquiry images" on storage.objects;
create policy "public upload enquiry images" on storage.objects for insert to anon with check (bucket_id='enquiry-images');
drop policy if exists "public read enquiry images" on storage.objects;
create policy "public read enquiry images" on storage.objects for select using (bucket_id='enquiry-images');
drop policy if exists "authenticated manage enquiry images" on storage.objects;
create policy "authenticated manage enquiry images" on storage.objects for all to authenticated using (bucket_id='enquiry-images') with check (bucket_id='enquiry-images');
